export const authorsById = new Map(authors.map((a) => [a.id, a]))
export const categoriesById = new Map(categories.map((c) => [c.id, c]))

export function getAuthor(id: string): Author {
  const author = authorsById.get(id)
  if (!author) throw new Error(`Unknown author: ${id}`)
  return author
}

export function getCategory(id: string) {
  return categoriesById.get(id as never)
}

export function getProductBySlug(slug: string) {
  return products.find((p) => p.slug === slug)
}

export function relatedProducts(product: Product, count = 4): Product[] {
  const sameCategory = products.filter(
    (p) => p.id !== product.id && p.categoryId === product.categoryId,
  )
  const sameAuthor = products.filter(
    (p) => p.id !== product.id && p.authorId === product.authorId && !sameCategory.includes(p),
  )
  return [...sameCategory, ...sameAuthor].slice(0, count)
}
